/**
 * Размеры оболочки, которые нужны не только самой оболочке.
 *
 * Высота шапки живёт здесь, потому что от неё зависит любой липкий элемент внутри страницы: панель
 * редактора, прилипая к нулю, уезжала **под** шапку и становилась невидимой — ровно та жалоба, из-за
 * которой за форматированием приходилось прокручивать страницу вверх.
 */
export const HEADER_HEIGHT = 68;

/**
 * К чему прилипать элементу, который должен стоять **под шапкой**.
 *
 * Не число, а переменная, потому что шапка теперь уезжает при прокрутке вниз: с жёстко записанными
 * 68 пикселями панель редактора осталась бы висеть там, где шапки уже нет, и над ней открылась бы
 * полоса проезжающего текста. Значение переменной проставляет `AppLayout`: высота шапки, когда она
 * видна, и ноль, когда убрана.
 */
export const STICKY_TOP = 'var(--app-sticky-top, 68px)';
