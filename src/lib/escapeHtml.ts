/**
 * Экранирование текста, который склеивается в разметку строками.
 *
 * Написано было дважды — в `knowledgeBase/wikiLinks.ts` и в `library/fb2.ts`, — и версии
 * расходились: одна экранировала кавычку, другая нет. Расхождение как раз того рода, из-за которого
 * дыра появляется в одном месте и не появляется в другом, а заметить это нечем.
 *
 * Кавычка экранируется всегда, даже когда значение идёт в текст, а не в атрибут: место, куда попадёт
 * строка, знает вызывающий, а ошибиться здесь дешевле в сторону лишнего `&quot;`.
 */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
