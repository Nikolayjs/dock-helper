import { describe, expect, it } from 'vitest';

import { plural, withPlural } from './plural';

const код = (n: number) => plural(n, 'код', 'кода', 'кодов');

describe('русская форма при числе', () => {
  it('единственное — только у единицы и у чисел, кончающихся на неё', () => {
    expect(код(1)).toBe('код');
    expect(код(21)).toBe('код');
    expect(код(101)).toBe('код');
  });

  it('от двух до четырёх — вторая форма', () => {
    expect([2, 3, 4, 22, 34, 103].map(код)).toEqual(['кода', 'кода', 'кода', 'кода', 'кода', 'кода']);
  });

  it('от пяти до двадцати — третья, и ноль тоже', () => {
    expect([0, 5, 9, 10, 20, 100].map(код)).toEqual(['кодов', 'кодов', 'кодов', 'кодов', 'кодов', 'кодов']);
  });

  it('вторая десятка — исключение целиком: 11–14 не «кода»', () => {
    // Ровно здесь ошибается наивное правило «смотрим последнюю цифру».
    expect([11, 12, 13, 14, 111, 112].map(код)).toEqual(['кодов', 'кодов', 'кодов', 'кодов', 'кодов', 'кодов']);
  });

  it('число подставляется вместе с формой', () => {
    expect(withPlural(12439, 'код', 'кода', 'кодов')).toBe('12439 кодов');
    expect(withPlural(1, 'препарат', 'препарата', 'препаратов')).toBe('1 препарат');
  });
});
