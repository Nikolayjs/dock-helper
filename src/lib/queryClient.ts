import { MutationCache, QueryClient } from '@tanstack/react-query';
import { notifications } from '@mantine/notifications';

/**
 * Ошибка любой мутации показывается врачу — по умолчанию и для всех сразу.
 *
 * До этого формы отдавали `onSubmit` без `try/catch`, и при недоступном сервере получалось худшее из
 * возможного: необработанное отклонение в консоли, ни тоста, ни перехода, и снятая охрана от ухода
 * со страницы. Врач жал «Сохранить», не происходило ничего, он уходил — приём потерян.
 *
 * Обработчик стоит в кэше мутаций, а не в каждом вызове: так он покрывает и те мутации, которые
 * появятся позже. Свой `onError` у конкретной мутации его не отменяет — оба вызываются, и
 * специальное сообщение всегда можно добавить рядом.
 */
export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      retry: 1,
      refetchOnWindowFocus: false,
      /**
       * Пять минут «свежести» вместо нуля.
       *
       * По умолчанию React Query считает данные устаревшими сразу, и каждый заход в раздел тянул
       * список заново: справочник препаратов — это полторы тысячи записей, и на мобильном интернете
       * тоже. При этом список **уже** обновляется точечно там, где это важно: любая правка сама
       * помечает свой кэш устаревшим (`invalidate` в общем скелете ресурса), а удаление ещё и
       * подменяет строку сразу. То есть пять минут — это про чужие правки в соседней вкладке, а не
       * про свои.
       *
       * Справочникам, которые вообще не меняются в сеансе (специальности, МКБ-10), уже стоит
       * `staleTime: Infinity` на своих запросах — общее значение их не касается.
       */
      staleTime: 5 * 60 * 1000,
    },
  },
  mutationCache: new MutationCache({
    onError: (error) => {
      notifications.show({
        color: 'red',
        title: 'Не удалось сохранить',
        message: error instanceof Error ? error.message : 'Неизвестная ошибка.',
      });
    },
  }),
});
