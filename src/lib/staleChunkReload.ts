/**
 * Вкладка, пережившая деплой, перезагружается сама — один раз.
 *
 * Каждая страница приложения приезжает отдельным файлом в момент нажатия, а имя файла содержит
 * отпечаток содержимого. Деплой пересобирает образ целиком, старых файлов на сервере не остаётся —
 * и вкладка, открытая до деплоя, просит по старому имени то, чего больше нет.
 *
 * Ответ при этом приходит **успешный**: пропавший адрес отдаётся возвратом SPA, то есть страницей
 * `index.html` с типом `text/html` (замер на бою: 200, 69 005 байт вместо стиля). Применить HTML
 * как стиль браузер отказывается — с `X-Content-Type-Options: nosniff` иначе и нельзя, — срабатывает
 * `onerror` у `<link>`, и Vite превращает это в `vite:preloadError`. Отсюда и текст «Unable to
 * preload CSS», в котором нет ни слова про 404: запрос удался, не подошёл ответ.
 *
 * Перезагрузка эту ситуацию лечит целиком: свежий `index.html` называет новые имена.
 *
 * **Перезагрузка ровно одна.** Если файла нет и после неё — сервер лежит, деплой на середине,
 * связи нет, — второй раз мы не перезагружаем, а отдаём ошибку экрану «Страница не открылась»: у
 * него есть кнопка «Перезагрузить» и кнопка «На дашборд». Молчаливый цикл перезагрузок хуже
 * честной ошибки: он выглядит как сломавшееся приложение и не оставляет способа уйти.
 */
const MARK = 'medassist:stale-chunk-reload';

/** Сколько времени отметка о перезагрузке считается свежей. */
export const RELOAD_COOLDOWN_MS = 30_000;

/**
 * Перезагружаться ли сейчас. Вынесено отдельно от обработчика, потому что решение здесь и есть вся
 * логика: с хранилищем разговаривает вызывающий, а проверяется правило.
 */
export function shouldReload(now: number, lastReloadAt: string | null): boolean {
  if (!lastReloadAt) return true;
  const previous = Number(lastReloadAt);
  // Испорченная отметка не должна запрещать перезагрузку навсегда — считаем, что её не было.
  if (!Number.isFinite(previous)) return true;
  return now - previous > RELOAD_COOLDOWN_MS;
}

/** Хранилище может быть недоступно (приватное окно, запрет данных сайта) — это не повод падать. */
function readMark(): string | null {
  try {
    return sessionStorage.getItem(MARK);
  } catch {
    return null;
  }
}

function writeMark(value: string): void {
  try {
    sessionStorage.setItem(MARK, value);
  } catch {
    // Без отметки перезагрузка возможна повторно — но она и так возможна только по событию Vite,
    // а событие приходит от нажатия врача, а не само по себе.
  }
}

export function listenForStaleChunks(): void {
  window.addEventListener('vite:preloadError', (event) => {
    const now = Date.now();
    if (!shouldReload(now, readMark())) return;
    // preventDefault гасит выброс ошибки: перезагрузка уже назначена, и показывать экран ошибки
    // на долю секунды перед ней незачем.
    event.preventDefault();
    writeMark(String(now));
    window.location.reload();
  });
}
