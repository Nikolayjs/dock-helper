/**
 * Полоса заголовка установленного приложения красится в цвет **шапки приложения**.
 *
 * У окна PWA верхнюю полосу рисует система, а цвет берёт из `theme-color`. В манифесте стоял
 * фирменный синий — и на тёмной теме с тёплыми обоями врач получал ярко-синюю планку над
 * коричневым приложением: единственное место окна, не имеющее к нему никакого отношения.
 *
 * Статическим значением это не чинится: у приложения две темы и подкраска под обои, то есть цвет
 * шапки — не константа, а результат настроек врача. Поэтому цвет **спрашивается у самой шапки**:
 * что бы ни насчитали тема и обои, полоса окна получает ровно то же. Двух источников правды при
 * этом не появляется — источник один, и он же нарисован на экране.
 *
 * До первой отрисовки и на публичном сайте, где шапки приложения нет вовсе, работают две меты из
 * `index.html`, объявленные через `media`: светлая и тёмная. **Своя мета вставляется первой** —
 * браузер берёт первую подходящую по документу, — и появляется только тогда, когда есть что в неё
 * записать: пустая или поставленная заранее, она перебила бы обе объявленные и покрасила полосу
 * не тем.
 *
 * **Посчитанный цвет запоминается на устройстве и ставится снова при следующем запуске — до того,
 * как приложение вообще начнёт грузиться** (inline-скрипт в `index.html`). Без этого на телефоне
 * полоса не перенимала тему приложения: телефон в светлой системной теме, приложение в тёмной — и до
 * первой отрисовки действует мета для светлой. Настольный браузер подхватывает мету, вставленную
 * позже, и там расхождения не видно; установленное на телефон приложение читает `theme-color` при
 * запуске и к позднему изменению может не вернуться. Поэтому при запуске в документе уже стоит
 * ровно тот цвет, каким шапка была в прошлый раз, а расчёт по живой шапке только уточняет его.
 *
 * Ключ **не** синхронизируется между устройствами намеренно: цвет — про шапку в этом окне, а тема
 * (`mantine-color-scheme-value`) и так хранится на устройстве.
 *
 * **Тот же цвет уезжает кукой — для манифеста.** Установленное на Android приложение (WebAPK в
 * Chrome) красит строку состояния цветом `theme_color` из **манифеста**, а мету страницы не
 * смотрит. Проверено на телефоне: та же страница во вкладке Chrome даёт тёмную панель, а в
 * приложении бар белый — ровно `theme_color`, каким он был в манифесте. Поэтому манифест отдаёт
 * сервер и подставляет в него цвет из куки; ссылка на манифест стоит с `use-credentials`, иначе
 * браузер запрашивает его без кук. Chrome сверяет манифест при запуске приложения не чаще раза в
 * сутки и, найдя разницу, пересобирает приложение — так что смена темы доезжает до бара с задержкой,
 * а переустановка подхватывает цвет сразу.
 */

const MARK = 'data-app-theme-color';

/** Читается inline-скриптом в `index.html` — имя там повторено буквально, менять оба вместе. */
export const THEME_COLOR_STORAGE_KEY = 'medassist:theme-color';

/** Читает сервер при отдаче манифеста (`app.controller.ts` в бэкенде) — имя повторено там буквально. */
export const THEME_COLOR_COOKIE = 'medassist-theme-color';

/** Год: кука обязана пережить любой перерыв в работе, иначе следующая установка выйдет с белым баром. */
const COOKIE_MAX_AGE = 60 * 60 * 24 * 365;

export function themeColorCookie(color: string, secure: boolean): string {
  return `${THEME_COLOR_COOKIE}=${encodeURIComponent(color)}; path=/; max-age=${COOKIE_MAX_AGE}; SameSite=Lax${secure ? '; Secure' : ''}`;
}

/**
 * Цвет шапки — в `#rrggbb`, и это не косметика.
 *
 * Под обоями поверхность считается через `color-mix`, а такой цвет браузер возвращает записью
 * `color(srgb 0.188 0.151 0.138)`. Спецификация `theme-color` принимает любой CSS-цвет, но
 * полагаться на то, что его разберёт и **система**, рисующая полосу окна, не стоит: не разберёт —
 * полоса останется прежней, и понять почему будет не по чему. Шестнадцатеричную запись понимают
 * все.
 *
 * Возвращает `null` для всего, чего не знает, — и для полупрозрачного: система ждёт сплошной цвет,
 * а шапка приложения сплошная всегда.
 */
export function toHexColor(color: string): string | null {
  const hex = (r: number, g: number, b: number) =>
    '#' + [r, g, b].map((v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('');

  const rgb = color.match(/^rgba?\(\s*([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)\s*(?:[,/]\s*([\d.%]+)\s*)?\)$/i);
  if (rgb) {
    const alpha = rgb[4];
    if (alpha !== undefined && Number.parseFloat(alpha) < (alpha.endsWith('%') ? 90 : 0.9)) return null;
    return hex(Number(rgb[1]), Number(rgb[2]), Number(rgb[3]));
  }

  const srgb = color.match(/^color\(\s*srgb\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*(?:\/\s*([\d.]+)\s*)?\)$/i);
  if (srgb) {
    if (srgb[4] !== undefined && Number(srgb[4]) < 0.9) return null;
    return hex(Number(srgb[1]) * 255, Number(srgb[2]) * 255, Number(srgb[3]) * 255);
  }

  return /^#[0-9a-f]{6}$/i.test(color) ? color.toLowerCase() : null;
}

export function syncThemeColorMeta(): void {
  const header = document.querySelector<HTMLElement>('[class*="AppShell-header"]');
  if (!header) return;

  const color = toHexColor(getComputedStyle(header).backgroundColor);
  if (!color) return;

  let meta = document.head.querySelector<HTMLMetaElement>(`meta[${MARK}]`);
  if (!meta) {
    meta = document.createElement('meta');
    meta.name = 'theme-color';
    meta.setAttribute(MARK, '');
    document.head.prepend(meta);
  }
  if (meta.content !== color) meta.content = color;

  try {
    if (localStorage.getItem(THEME_COLOR_STORAGE_KEY) !== color) localStorage.setItem(THEME_COLOR_STORAGE_KEY, color);
    // `Secure` только на https: на локальном стенде по http такую куку браузер просто не запишет.
    document.cookie = themeColorCookie(color, location.protocol === 'https:');
  } catch {
    // Хранилище может отказать (приватное окно, запрет на данные сайта): тогда при следующем
    // запуске работают меты из `index.html`, как и раньше.
  }
}
