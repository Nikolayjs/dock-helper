import { normalizeDrugName } from '../drugs/drugIndex';
import type { DrugSummary } from '../drugs/types';

/**
 * Комбинированный препарат и правила его компонентов.
 *
 * Правило взаимодействия написано на одно МНН, а половина того, что пациент реально пьёт, — это
 * комбинации: «Ибуклин» (ибупрофен + парацетамол), «Цитрамон», «Лориста Н», любой КОК. Своих правил
 * у них нет и быть не может: писать двадцать шесть ибупрофеновых правил заново на каждую комбинацию
 * значит завести полторы тысячи строк, которые разъедутся с оригиналом при первой же правке.
 * Поэтому состав раскрывается здесь, в проверке, а в сиде остаётся по одному правилу на компонент.
 *
 * Замер до правки: из 164 комбинаций справочника у 108 не было ни одного своего правила, тогда как
 * у компонента правила есть. «Ибуклин + Варфарин» отвечало «взаимодействий не найдено», а
 * «Нурофен + Варфарин» — двадцатью шестью правилами. Это та же дыра, что была с Корвалолом, только
 * не на одной карточке, а на сотне.
 */

/** Состав комбинации: МНН перечисляет компоненты через «/». Для монопрепарата — пустой список. */
export function componentsOf(inn: string): string[] {
  if (!inn.includes('/')) return [];
  return inn
    .split('/')
    .map((part) => normalizeDrugName(part))
    .filter(Boolean);
}

/**
 * Местные формы, к которым системные правила компонента не относятся.
 *
 * Различается это по коду ATC, а не по списку названий и не по полю «формы»: код есть у каждой
 * карточки, он и означает путь введения, а список наружных препаратов пришлось бы дополнять руками
 * при каждом пополнении справочника — и он молча отставал бы. Сверено со списком форм по всем 164
 * комбинациям: расхождений пять, и в четырёх из них прав именно код.
 *
 * Без этого «Тержинан» — вагинальные суппозитории — наследовал бы двенадцать системных правил
 * преднизолона, а «Тобрадекс», глазные капли, — правила дексаметазона про желудочное кровотечение.
 *
 * **`S01E` — исключение из исключения, и оно не косметическое.** Это средства от глаукомы, то есть
 * тимолол и его комбинации. Оба правила тимолола в справочнике написаны ровно про то, что
 * «глазные капли с неселективным бета-блокатором всасываются системно»: с сальбутамолом — потеря
 * бронхолитического эффекта, с верапамилом — брадикардия и блокада. Убрать их у «Ганфорта» значило
 * бы выбросить предупреждения, которые для этой формы и написаны.
 */
const LOCAL_ATC_PREFIXES = [
  'D', // наружные средства
  'S02', // ушные
  'S03', // глазные и ушные вместе
  'G01', // вагинальные противомикробные
  'A01', // стоматологические
  'R01', // назальные
  'R02', // средства для горла
  'C05A', // местные при геморрое
  'M02', // местные при боли в суставах и мышцах
  'P03', // наружные противопаразитарные
];

export function isLocalRoute(atcCode: string): boolean {
  const code = atcCode.trim().toUpperCase();
  if (!code) return false;
  // Глазные: местные, кроме средств от глаукомы — те всасываются, см. комментарий выше.
  if (code.startsWith('S01')) return !code.startsWith('S01E');
  return LOCAL_ATC_PREFIXES.some((prefix) => code.startsWith(prefix));
}

/**
 * МНН, по которым препарат участвует в проверке: он сам и, у системной комбинации, её компоненты.
 *
 * Незнакомый препарат (в справочнике карточки нет) участвует по тому, что набрали, — как и раньше:
 * проверка не должна становиться слабее там, где справочник неполон.
 */
export function matchKeysFor(inn: string, drug: DrugSummary | null): string[] {
  const own = normalizeDrugName(inn);
  if (!drug || isLocalRoute(drug.atcCode)) return [own];
  return [own, ...componentsOf(drug.inn).filter((part) => part !== own)];
}
