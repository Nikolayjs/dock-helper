/**
 * Одно **значение** одной аббревиатуры.
 *
 * Строка — это пара «сокращение + значение», а не сокращение: «ОА» — это и остеоартроз, и общий
 * анализ, «СД» — сахарный диабет и сердечная деятельность. Справочник, показывающий одно значение
 * из двух, отвечает верно ровно наполовину, и заметить это нельзя — второго ответа врач просто не
 * увидит. Поэтому одно и то же `short` встречается в списке столько раз, сколько у него смыслов.
 */
export interface Abbreviation {
  id: string;
  short: string;
  full: string;
  /** Одно-два предложения: где встречается, с чем не спутать. Может быть пустым. */
  meaning: string;
  /** Англоязычный оригинал или соответствие: `COPD`, `eGFR`. Может быть пустым. */
  origin: string;
  category: string;
  /** Пусто у записей врача — по этому признаку и отличается своя строка от заводской. */
  seedKey: string;
  createdAt: string;
  updatedAt: string;
}

export interface AbbreviationInput {
  short: string;
  full: string;
  meaning: string;
  origin: string;
  category: string;
}
