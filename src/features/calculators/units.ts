import { plural } from '../../lib/plural';

/**
 * Единица измерения при числе — там, где она склоняется.
 *
 * Склоняется ровно одна из встречающихся: «лет». Калькулятор подписывает поле возраста именно так,
 * и в самом поле «54 лет» ещё сходит за подпись единицы, но эти же слова уходят **в заметку визита**
 * — то есть в карту пациента, где «возраст 54 лет» читается как строка, собранную машиной. Та же
 * причина, по которой склоняется глагол в предупреждении об удалении.
 *
 * Остальные единицы (кг, см, мкмоль/л) не склоняются вовсе, поэтому общего правила здесь и не нужно.
 */
export function withUnit(value: number, unit?: string): string {
  const number = String(value).replace('.', ',');
  if (!unit) return number;
  if ((unit === 'лет' || unit === 'год') && Number.isInteger(value)) {
    return `${number} ${plural(value, 'год', 'года', 'лет')}`;
  }
  return `${number} ${unit}`;
}
