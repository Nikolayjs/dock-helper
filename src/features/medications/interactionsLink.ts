/**
 * Адрес проверки взаимодействий с уже подставленной терапией.
 *
 * Транспорт был готов давно: `InteractionsCheck` принимает `?drugs=` через запятую, разрешает
 * торговые названия и раскрывает комбинации по «/». Не хватало **отправителя** — список постоянной
 * терапии врач держал в голове и на приёме набирал заново, то есть чаще всего не набирал.
 *
 * Раздел живёт вкладкой справочника, поэтому адрес именно такой: `/interactions` перенаправляется
 * сюда же, но лишний переход стоил бы мигания пустой проверкой.
 */
export function interactionsHref(names: string[]): string {
  const drugs = names
    .map((name) => name.trim())
    // Запятая — разделитель самого списка: имя с запятой разорвало бы его на два неизвестных
    // препарата, то есть проверка соврала бы дважды вместо того, чтобы честно не узнать одно.
    .map((name) => name.replace(/\s*,\s*/g, ' '))
    .filter(Boolean)
    .join(',');
  return `/drugs?tab=interactions&drugs=${encodeURIComponent(drugs)}`;
}
