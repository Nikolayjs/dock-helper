/**
 * Разбор **настоящего** распознанного бланка, а не выдуманных строк.
 *
 * Строки ниже — дословный вывод того самого Tesseract, что стоит на бою, на копии бланка
 * лаборатории «Прогрессивные Медицинские Технологии». Держать их фикстурой стоит потому, что все
 * ошибки здесь чужие и не выдумываются: колонка отделена палкой, у чисел прилипает скобка, коды
 * теста приезжают то латиницей, то кириллицей (`RBC` → `ВВС`), а строки таблицы норм («Дети до 15»)
 * выглядят для разборщика такими же строками с числом, как и настоящие показатели.
 *
 * Мерить по одним названиям — самообман: в бланке важны **значения**, и проверяется здесь именно
 * то, сколько значений доехало до анализатора.
 */

