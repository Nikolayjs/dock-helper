import { describe, expect, it } from 'vitest';

import { matchAnalytes } from './matchAnalytes';
import { parseLabValues } from './parseLabValues';
import type { LabTestDefinition } from '../types';

/**
 * Бланк с боя, распознанный **как есть**.
 *
 * Это дословный текст из приложения врача — со скриншота просмотрщика, а не из файла. Он плох, и в
 * этом весь смысл фикстуры: сюда попали ровно те поломки, которых не выдумать за столом.
 *
 * - Заглавная не опозналась: «Глюкоза» → «тюкоза», «Лейкоциты» → «Ледкоциты».
 * - «Отриц.» набрано курсивом, и курсивные `т`, `и`, `ц` неотличимы от латинских `m`, `u`, `n` —
 *   Tesseract читает `Orpmu.`, `Orpau.`, и слово перестаёт быть отрицательным результатом.
 * - Колонка норм («Здоровые люди») приклеивается к хвосту почти каждой строки.
 * - Значение `0.1` прочиталось как `oa` — вот это не спасти ничем, и притворяться не нужно.
 */
const REAL_OCR = [
  'Смакова ДН (2% - 201912130358 (1).pdf',
  'Независимая лаборатория Воровского, 60 (касса 1)',
  "'Прогрессивные Медицинские Технологии\"",
  'Лабораторное исследование',
  '201912130358',
  'ж',
  'задания: 09.10.2017 Bospacr: 2',
  'Никиий | Верхний',
  'Результат Нормы предел | пред',
  'тюкоза Отриц. Здоровые люди',
  'Белок oa Здоровые люди',
  "'Bunupy6un Orpmu.",
  'Ypo6unuwosen Отриц. Здоровые кам',
  'pH 70 Здоровые люди',
  'Эритроциты евкция на Orpau. здоровые люди',
  'Кетоны Orpmu, Здоровые люди',
  "'Нитриты Orpmu.",
  '`Лебкощиты (реакция на Отриц. Здоровые nosy',
  '"Прозрачность Слабо мутная Здоровые люди',
  'Дети 20 3x лет ворослые',
  'Убельный вес 1026 1002',
  'Цвет Желтая',
  'Аскорбиновая кислота Отриц.',
  'Эритроциты Отриц. enn Здоровые люди',
  'Дети до 15 лет',
  '`Ледкоциты Дети до 15 пет',
  'Бактерии | отн',
];

const URINALYSIS = {
  id: 'oam',
  title: 'Общий анализ мочи',
  shortTitle: 'ОАМ',
  description: '',
  parameters: [
    { key: 'ph', label: 'pH', unit: '', range: { min: 5, max: 7 } },
    { key: 'protein', label: 'Белок', unit: 'г/л', range: { min: 0, max: 0.033 } },
    { key: 'glucose', label: 'Глюкоза', unit: 'ммоль/л', range: { min: 0, max: 0.8 } },
    { key: 'bilirubin', label: 'Билирубин', unit: 'мкмоль/л', range: { min: 0, max: 8.5 } },
    { key: 'urobilinogen', label: 'Уробилиноген', unit: 'мкмоль/л', range: { min: 0, max: 34 } },
    // Псевдонимы у заводского анализатора настоящие: «Кетоны» — то, как это печатают лаборатории.
    { key: 'ketones', label: 'Кетоновые тела', aliases: ['KET', 'Кетоны', 'Ацетон'], unit: 'ммоль/л', range: { min: 0, max: 0.5 } },
    { key: 'nitrites', label: 'Нитриты', unit: 'мг/дл', range: { min: 0, max: 0.1 } },
    { key: 'bloodReaction', label: 'Эритроциты (реакция на гемоглобин)', unit: 'мг/л', range: { min: 0, max: 0.3 } },
    { key: 'ascorbicAcid', label: 'Аскорбиновая кислота', unit: '', range: { min: 0, max: 1 } },
    { key: 'specificGravity', label: 'Удельный вес', unit: '', range: { min: 1003, max: 1035 } },
    { key: 'erythrocytes', label: 'Эритроциты', unit: 'ед/мкл', range: { min: 0, max: 17 } },
    { key: 'bacteria', label: 'Бактерии', unit: '', range: { min: 0, max: 1 } },
  ],
} as unknown as LabTestDefinition;

const matched = () => {
  const plan = matchAnalytes(parseLabValues(REAL_OCR, { ocr: true }), [URINALYSIS]);
  return (plan.fills[0]?.matches ?? []).map((match) => match.param.label);
};

describe('бланк с боя, распознанный как есть', () => {
  /*
   * Четыре строки, которые терялись **целиком** из-за одного слова: «Отриц.», прочитанного
   * латиницей. Их потеря и была главной — не «плохо узнаётся», а «не доходит вовсе».
   */
  it('строки с искажённым «Отриц.» доходят до разбора', () => {
    const found = matched();
    expect(found).toContain('Билирубин');
    expect(found).toContain('Кетоновые тела');
    expect(found).toContain('Нитриты');
    expect(found).toContain('Эритроциты (реакция на гемоглобин)');
  });

  /*
   * Сколько всего вытаскивается из этой картинки — числом, чтобы правка, которая молча ухудшит
   * разбор, была видна. Семь показателей из двадцати двух строк бланка: остальное распознавание
   * испортило так, что восстанавливать нечего, и **притворяться, что можно, нельзя**.
   */
  it('с плохой картинки доезжает семь показателей, и это потолок для неё', () => {
    expect(matched().length).toBeGreaterThanOrEqual(7);
  });

  /*
   * «тюкоза» — это «Глюкоза», у которой распознавание съело заглавную и половину первой буквы.
   * Строка **доходит до разбора** (регистру в распознанном тексте веры нет), но до показателя не
   * дотягивается: две правки на семь букв — это уже не опечатка, а другое слово. Пусть лучше висит
   * в «не совпало», чем ляжет в соседний показатель.
   */
  it('строка со строчной первой буквой доходит до разбора, но не угадывается', () => {
    const names = parseLabValues(REAL_OCR, { ocr: true }).map((analyte) => analyte.name);
    expect(names).toContain('тюкоза');
    expect(matched()).not.toContain('Глюкоза');
  });

  it('то, что читалось и раньше, читается по-прежнему', () => {
    const found = matched();
    expect(found).toContain('Удельный вес');
    expect(found).toContain('Аскорбиновая кислота');
    expect(found).toContain('Эритроциты');
  });

  /*
   * `Белок oa` — значение не прочиталось вовсе, и выдумывать его нельзя: `oa` это не число ни в
   * каком приближении. Строка честно остаётся без значения.
   */
  it('нечитаемое значение не выдумывается', () => {
    expect(matched()).not.toContain('Белок');
  });
});
