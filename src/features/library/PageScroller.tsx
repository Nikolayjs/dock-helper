import type { ReactNode } from 'react';

/**
 * Рамка с постраничным документом внутри: прокрутка вбок и вниз, страницы по центру.
 *
 * Центрирование и переполнение вместе — ловушка. `align-items: center` на самой прокручиваемой
 * рамке выносит слишком широкий лист за **оба** её края, а левый выступ достать нечем: `scrollLeft`
 * меньше нуля не бывает, и прокрутка вправо только уводит дальше. Замер на телефоне 390 px: лист
 * 714 px в рамке 350 px, левый край на −162 px, `scrollWidth` 532 вместо 714 — 182 px листа не
 * существует ни при какой прокрутке.
 *
 * Поэтому центрируется не лист в рамке, а лист в **дорожке**: она шире рамки ровно настолько,
 * насколько широки страницы (`width: fit-content`), и не уже рамки (`min-width: 100%`). Пока
 * страницы помещаются, дорожка равна рамке и центрирование работает как раньше; когда не
 * помещаются — переполнения нет вовсе, есть обычная прокрутка вбок.
 *
 * `scrollbar-gutter: stable` здесь — не косметика, а разрыв петли. «По ширине» меряет `clientWidth`
 * рамки; без постоянного запаса под полосу прокрутки этот замер зависит от того, появилась ли
 * полоса, а появляется она от того, каким вышел масштаб. Замер на телефоне 390 px: лист
 * устаканивался на 357 px в рамке 350 — на 7 px шире, чем помещалось. Там, где полосы наложенные
 * (телефон), правило не занимает ничего.
 *
 * `overscroll-behavior-x: contain` — чтобы смах вбок на последней странице листал документ, а не
 * уводил браузер назад по истории.
 */
interface PageScrollerProps {
  /** Прокручиваемая рамка: по ней читалка ищет страницы и мерит доступную ширину. */
  frameRef: (element: HTMLDivElement | null) => void;
  maxHeight: string;
  /**
   * Сколько сверху занимает лежащая на листе панель.
   *
   * Отступ идёт дорожке, а `scroll-padding-top` — рамке: первый убирает панель с первой страницы,
   * второй нужен переходу к странице (`scrollIntoView`), иначе верх выбранной страницы вставал бы
   * ровно под панель — то есть выбранная страница начиналась бы за ней.
   */
  topInset?: number;
  children: ReactNode;
}

export function PageScroller({ frameRef, maxHeight, topInset = 0, children }: PageScrollerProps) {
  return (
    <div
      ref={frameRef}
      style={{
        maxHeight,
        width: '100%',
        overflow: 'auto',
        overscrollBehaviorX: 'contain',
        scrollbarGutter: 'stable',
        scrollPaddingTop: topInset,
      }}
    >
      <div
        style={{
          width: 'fit-content',
          minWidth: '100%',
          display: 'flex',
          flexDirection: 'column',
          alignItems: 'center',
          padding: `${4 + topInset}px 0 4px`,
        }}
      >
        {children}
      </div>
    </div>
  );
}
