import type { Book } from './types';

/**
 * Два решения, которые принимает полка, — и оба про **общий файл**.
 *
 * Вынесены сюда из хука не ради чистоты: их надо проверять тестом, а ошибка в любом из них не
 * падает и не видна на экране. Первая молча заводит вторую запись той же книги, вторая — молча
 * стирает файл, которым пользуется соседняя.
 */

/** Та же книга уже на полке? Отвечает содержимое, а не имя файла: «Учебник (1).pdf» — та же книга. */
export function findByFingerprint(books: Book[], sha256: string): Book | undefined {
  return books.find((book) => book.sha256 === sha256);
}

/**
 * Ссылается ли на файл кто-то ещё, кроме удаляемой записи.
 *
 * Файл общий по отпечатку: две записи одной книги делят его. Удаляя свою, читатель не должен
 * оставить соседнюю без содержимого — а заметить это можно было бы только открыв её.
 */
export function fileStillUsed(books: Book[], removedId: string, sha256: string): boolean {
  return books.some((book) => book.id !== removedId && book.sha256 === sha256);
}
