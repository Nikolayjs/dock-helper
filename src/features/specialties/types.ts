/**
 * Специальность врача и то, что ей относится в трёх справочниках.
 *
 * Приходит с сервера (`GET /specialties`) целиком: девятнадцать записей, три килобайта. Отбор
 * считается здесь, на фронте, потому что сами справочники уже лежат в памяти браузера — просить
 * сервер отфильтровать то, что и так под рукой, значило бы завести запрос на каждое нажатие
 * тумблера.
 */
export interface Specialty {
  /** Неизменный ключ: он и лежит в профиле врача. */
  id: string;
  name: string;
  /** Разделы базы знаний — первый тег клинической рекомендации. Пусто — раздела нет вовсе. */
  guidelineSections: string[];
  /** Разделы формуляра — значение `category` у препарата. */
  drugCategories: string[];
  /** Блоки МКБ-10, названные первым кодом диапазона: `I20` — это блок `I20–I25`. */
  icdBlocks: string[];
}
