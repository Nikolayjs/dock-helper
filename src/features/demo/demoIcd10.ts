/** Тот же отбор, что делает сервер: по коду и по названию, без учёта регистра. */
export function searchDemoIcd10(query: string, limit: number): DemoIcd10Entry[] {
  const needle = query.trim().toLowerCase();
  if (!needle) return [];
  return DEMO_ICD10.filter(
    (entry) => entry.code.toLowerCase().includes(needle) || entry.name.toLowerCase().includes(needle),
  ).slice(0, limit);
}
