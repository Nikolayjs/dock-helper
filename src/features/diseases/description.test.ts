import { describe, expect, it } from 'vitest';

import { descriptionToHtml } from './description';

/**
 * Превращение старых описаний в разметку.
 *
 * Проверяется прежде всего то, ради чего функция и написана: абзацы, набранные пустыми строками,
 * обязаны остаться абзацами. Склеенный в один ком текст — это не «немного хуже выглядит», а
 * потеря структуры, причём необратимая после первого сохранения в редакторе.
 */
describe('старый обычный текст', () => {
  it('пустые строки становятся абзацами', () => {
    expect(descriptionToHtml('Этиология\n\nСимптоматика')).toBe('<p>Этиология</p><p>Симптоматика</p>');
  });

  it('одиночный перевод строки остаётся переводом строки внутри абзаца', () => {
    expect(descriptionToHtml('строка один\nстрока два')).toBe('<p>строка один<br>строка два</p>');
  });

  it('несколько пустых строк подряд не плодят пустых абзацев', () => {
    expect(descriptionToHtml('первый\n\n\n\nвторой')).toBe('<p>первый</p><p>второй</p>');
  });

  it('угловые скобки в тексте экранируются, а не выполняются', () => {
    // Иначе «АД <90/60» вырезало бы кусок текста, а вставленное из чужого источника — и того хуже.
    expect(descriptionToHtml('АД <90/60 мм рт. ст.')).toBe('<p>АД &lt;90/60 мм рт. ст.</p>');
  });

  it('CRLF из Windows разбирается так же, как LF', () => {
    expect(descriptionToHtml('первый\r\n\r\nвторой')).toBe('<p>первый</p><p>второй</p>');
  });
});

describe('готовая разметка', () => {
  it('не трогается', () => {
    const html = '<h3>Этиология</h3><p>Текст</p>';
    expect(descriptionToHtml(html)).toBe(html);
  });

  it('распознаётся по любому тегу, не только по первому символу', () => {
    expect(descriptionToHtml('Вступление <p>и абзац</p>')).toBe('Вступление <p>и абзац</p>');
  });
});

describe('пустое', () => {
  it('остаётся пустым — карточка покажет заглушку', () => {
    expect(descriptionToHtml('')).toBe('');
    expect(descriptionToHtml('   \n  ')).toBe('');
  });
});
