import { escapeHtml } from '../../lib/escapeHtml';

/**
 * Описание болезни в виде разметки — включая то, что было написано до появления редактора.
 *
 * Поле `description` завелось как простое текстовое, и в нём уже лежат настоящие записи врача:
 * семь тысяч знаков про болезнь Меньера, разбитые пустыми строками на разделы. Отдать такой текст
 * как разметку значит **склеить его в один абзац**: браузер переводы строк не показывает. Отдать
 * его редактору без превращения — то же самое, только необратимо: первое же сохранение запишет
 * склеенное обратно.
 *
 * Поэтому и просмотр, и редактор смотрят на текст через эту функцию: текст без единого тега
 * считается старым, и его абзацы восстанавливаются. Проверка простая — есть ли хоть один тег;
 * ошибиться она может только на тексте, где врач руками написал что-то вида `<...>`, и цена
 * ошибки — лишний экранированный фрагмент, а не потерянные абзацы.
 */
export function descriptionToHtml(description: string): string {
  const text = description.trim();
  if (!text) return '';
  if (/<[a-z][^>]*>/i.test(text)) return description;

  return text
    .split(/\r?\n\s*\r?\n/)
    .map((block) => block.trim())
    .filter(Boolean)
    .map((block) => `<p>${block.split(/\r?\n/).map(escapeHtml).join('<br>')}</p>`)
    .join('');
}
