/**
 * Одна нозология в справочнике заболеваний.
 *
 * Справочник не пересказывает ни МКБ-10, ни клинические рекомендации, а связывает их: строка
 * отвечает сразу на три вопроса — как болезнь называют (включая разговорное имя), каким кодом её
 * кодируют и где про неё читать.
 */
export interface Disease extends DiseaseSummary {
  /** Описание врача. Пусто — карточка показывает заглушку с приглашением дописать. */
  description: string;
}

/**
 * Запись списка: всё, кроме описания.
 *
 * Описание в список не едет намеренно — раздел заполняется как вики, и тексты растут. На этом уже
 * обжигалась база знаний: список отдавал 517 КБ, из которых 412 КБ были невидимые тексты, и ехало
 * это с каждой страницы раздела. Здесь та же пара, что у неё и у формуляра: сводка в списке,
 * полная запись по `id`.
 */
export interface DiseaseSummary {
  id: string;
  name: string;
  /** Прежнее, разговорное имя или аббревиатура — то, что сказал пациент или стоит в чужой выписке. */
  synonyms: string[];
  /** Рубрики МКБ-10. Пусто — однозначного кода нет, и карточка так и говорит. */
  icdCodes: string[];
  summary: string;
  category: string;
  /** Пусто у записей врача — по этому признаку своя строка отличается от заводской. */
  seedKey: string;
  /** Описано ли уже: сам текст в списке не едет, а видеть, что осталось заполнить, врачу нужно. */
  hasDescription: boolean;
  createdAt: string;
  updatedAt: string;
}

/** Короткая ссылка на болезнь: карточка кода МКБ-10 и обратные ссылки показывают именно её. */
export interface DiseaseLink {
  id: string;
  name: string;
  summary: string;
}

export interface DiseaseInput {
  name: string;
  synonyms: string[];
  icdCodes: string[];
  summary: string;
  description: string;
  category: string;
}
