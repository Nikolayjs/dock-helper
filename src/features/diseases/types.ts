/**
 * Одна нозология в справочнике заболеваний.
 *
 * Справочник не пересказывает ни МКБ-10, ни клинические рекомендации, а связывает их: строка
 * отвечает сразу на три вопроса — как болезнь называют (включая разговорное имя), каким кодом её
 * кодируют и где про неё читать.
 */
export interface Disease {
  id: string;
  name: string;
  /** Прежнее, разговорное имя или аббревиатура — то, что сказал пациент или стоит в чужой выписке. */
  synonyms: string[];
  /** Рубрики МКБ-10. Пусто — однозначного кода нет, и карточка так и говорит. */
  icdCodes: string[];
  summary: string;
  /** Описание врача. Пусто — карточка показывает заглушку с приглашением дописать. */
  description: string;
  category: string;
  /** `seedKey` клинической рекомендации об этой болезни или пусто. */
  guidelineKey: string;
  /**
   * `id` этой рекомендации в текущем рабочем пространстве — уже разрешённый сервером.
   *
   * Разрешает сервер, а не страница: сам `seedKey` намеренно вырезается из ответов, иначе редактор
   * вернул бы его обратно и валидация отклонила бы сохранение.
   */
  guidelineId: string;
  /** Пусто у записей врача — по этому признаку своя строка отличается от заводской. */
  seedKey: string;
  createdAt: string;
  updatedAt: string;
}

export interface DiseaseInput {
  name: string;
  synonyms: string[];
  icdCodes: string[];
  summary: string;
  description: string;
  category: string;
}
