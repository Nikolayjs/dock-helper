export type KnowledgeKind = 'guideline' | 'article';

/**
 * Документ базы знаний в том объёме, в каком его отдаёт список.
 *
 * Без `content`, и это не экономия на спичках: тело документа в списке не показывается, а весит
 * почти весь ответ. Замер на справочнике из 210 рекомендаций — 517 КБ против 100 КБ, а запрос идёт
 * с каждой страницы базы знаний. Та же пара типов, что `DrugSummary` и `Drug` у формуляра.
 */
export interface KnowledgeDocumentSummary {
  id: string;
  kind: KnowledgeKind;
  title: string;
  summary: string;
  tags: string[];
  /**
   * Обложка карточки — эскиз, а не сама картинка.
   *
   * Она приходит **в списке**, в отличие от текста, и это то же самое решение, только с другим
   * знаком: показать её нужно именно в списке, поэтому она едет отдельной колонкой и ужимается до
   * 640 px в редакторе (`cover.ts`). Вычислить её из текста на этой стороне нечем — текста здесь
   * нет.
   *
   * Пусто бывает двух видов. `null` — обложки не было, и редактор вправе предложить первую картинку
   * из текста. Пустая строка — врач обложку **убрал**, и возвращать её при следующем сохранении
   * значило бы спорить с ним.
   */
  coverDataUrl: string | null;
  author: string;
  createdAt: string;
  updatedAt: string;
}

/** Полный документ: приходит только с `GET /knowledge-documents/:id`. */
export interface KnowledgeDocument extends KnowledgeDocumentSummary {
  content: string;
}
