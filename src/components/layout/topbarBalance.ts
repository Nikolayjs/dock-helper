/**
 * Насколько широкими сделать боковые группы шапки, чтобы заголовок стоял посередине **окна**.
 *
 * Одного `flex: 1 1 0` мало: справа поиск, колокольчик и карточка врача — вместе шире логотипа
 * слева, и когда правой стороне не хватает её доли, она забирает недостающее у левой. Заголовок
 * между ними съезжает: замер давал 20 px при ширине окна 1300 и 95 px при 1150. Поэтому обеим
 * сторонам ставится `min-width` по более широкой из них.
 *
 * Расчёт вынесен из компонента отдельно и целиком, потому что ошибка здесь — не смещённый на
 * пиксель заголовок, а **автоколебание**: `min-width` меняет ширину стороны, `ResizeObserver`
 * будит замер, замер меняет `min-width`. В браузере это выглядит как «периодически появляется
 * горизонтальный скролл» и руками почти не ловится; тестом — ловится (см. проверку на устойчивость
 * в `topbarBalance.test.ts`).
 */

/** Ниже этого заголовок уже не прочитать, и уравнивать стороны ради него незачем. */
export const MIN_TITLE_WIDTH = 160;

export interface BalanceInput {
  /** Ширина содержимого левой группы — без тянущихся элементов, см. `data-elastic` в `Topbar`. */
  left: number;
  /** То же справа. */
  right: number;
  /** Ширина строки шапки: в неё обязаны поместиться обе стороны и заголовок. */
  container: number;
  /** Телефон: центрального заголовка там нет вовсе, и уравнивать нечего. */
  compact: boolean;
}

/**
 * Ноль означает «не задавать `min-width`»: стороны делят место сами и **имеют право сжиматься**.
 *
 * Потолок в половину свободного места — не перестраховка, а условие устойчивости: без него
 * `min-width` могла вытолкнуть стороны за контейнер, и следующий замер вернул бы уже другое
 * значение, с которого всё началось бы заново.
 */
export function balanceSides({ left, right, container, compact }: BalanceInput): number {
  // На телефоне центральный заголовок скрыт (`visibleFrom="sm"`), а заголовок раздела живёт внутри
  // левой группы и тянется по месту: уравнивать нечего, а `min-width` там и была источником
  // колебаний — она меняла ширину того самого элемента, по которому идёт замер.
  if (compact) return 0;
  if (container <= 0) return 0;

  const widest = Math.max(left, right, 0);
  const ceiling = Math.floor((container - MIN_TITLE_WIDTH) / 2);
  // Уравнивать стороны можно только пока обе помещаются вместе с заголовком: иначе жёсткая
  // `min-width` вытолкнет правую сторону за край окна, и вместо смещённого заголовка получится
  // горизонтальная прокрутка всей шапки.
  if (ceiling <= 0 || widest * 2 + MIN_TITLE_WIDTH > container) return 0;

  return Math.min(widest, ceiling);
}
