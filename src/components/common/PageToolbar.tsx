import type { ReactNode } from 'react';
import { Box, Card, Divider, Stack } from '@mantine/core';

/**
 * Верхушка страницы раздела: вкладки и всё, чем управляют содержимым, — на одной поверхности.
 *
 * До этого каждая страница решала сама, и получилось три разных вида: у заметок и калькуляторов
 * вкладки лежали внутри карточки со счётчиком и поиском, у пациентов и справочника — отдельно, на
 * фоне страницы, а у анализов и новостей на фоне висели ещё и две полосы кнопок подряд. Разделы
 * выглядели как куски разных приложений, и с обоями это особенно заметно: то, что лежит на фоне,
 * лежит на фотографии.
 *
 * **Правило одно: всё, что управляет страницей, образует один блок, приклеенный к содержимому, и
 * между управлением и данными ровно один разделитель.** Так устроены списки в Shopify Polaris
 * (вкладки видов живут внутри карточки списка, а не над ней), вкладки Material 3 (они прикреплены к
 * шапке и делят с ней поверхность), шапка репозитория в GitHub и панель вида в Notion и Linear —
 * одна полоса управления, одна черта, дальше данные. Разница между ними в мелочах, общее — именно
 * это: управление не висит отдельными островами.
 *
 * Порядок строк тоже общий и не случаен: сначала **где мы** (вкладки раздела), потом **что делаем с
 * тем, что видим** (счётчик, поиск, отбор, кнопки). Обратный порядок заставлял бы искать переключатель
 * раздела под кнопками этого же раздела.
 */
interface PageToolbarProps {
  /** Вкладки раздела — первая строка. Их может не быть: не у каждого раздела есть подразделы. */
  tabs?: ReactNode;
  /** Счётчик, поиск, отбор, кнопки — вторая строка. */
  children?: ReactNode;
  /**
   * Содержимое продолжается на этой же поверхности (список), и тогда черта отделяет его от
   * управления. Без него панель — самостоятельная карточка, а содержимое идёт ниже своими.
   */
  content?: ReactNode;
}

export function PageToolbar({ tabs, children, content }: PageToolbarProps) {
  return (
    <Card withBorder padding={0}>
      <Box p="md">
        <Stack gap="sm">
          {tabs}
          {children}
        </Stack>
      </Box>
      {content !== undefined && (
        <>
          {/* Ровно одна черта между управлением и данными: без неё поиск и первая строка списка
              читаются как одна группа, а с двумя чертами полоса управления распадается надвое. */}
          <Divider />
          {content}
        </>
      )}
    </Card>
  );
}
