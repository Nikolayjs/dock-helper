import { Stack, Loader } from '@mantine/core';

/**
 * Ожидание, пока страница получает свои данные, — **третья** фаза загрузки, и она тоже прыгала.
 *
 * `BootLoader` свёл первые две — проверку токена и загрузку чанка. Дальше страница монтируется,
 * оболочка появляется, и страница показывает уже свой лоадер: в половине разделов это был
 * `<Group justify="center" py="xl">`, то есть блок, прижатый к верху содержимого. Замер на телефоне
 * 390×844 при медленной сети (страница анализов): лоадер стоял на y=422 — центр экрана, — а потом
 * перескакивал на **y=228**, то есть вверх на 194 px, ровно в тот момент, когда врач на него
 * смотрит. Со стороны это выглядит так же, как прежняя жалоба: приложение будто загрузилось и
 * начало заново. Ловилось не везде: только там, где своя загрузка страницы успевала отрисоваться.
 *
 * Поэтому высоту здесь снова называет **одно** место, и величина другая, чем у `BootLoader`: к этой
 * фазе шапка уже нарисована и забрала свои 68 px сверху, а у содержимого есть собственные отступы.
 * Свободное место — это окно за вычетом того и другого, и центр ожидания — его центр. Ради того же
 * `BootLoader` теперь тоже отступает на высоту шапки: иначе первые две фазы центрировались бы по
 * всему окну, а третья — по остатку, и прыжок вернулся бы, только вчетверо меньше.
 *
 * Замер после правки: `BootLoader` встаёт на **y=456** (390×844) и **y=484** (1400×900), а блок
 * ожидания выходит ровно `окно − шапка − два отступа` (736 и 792 px) и начинается от верха области
 * содержимого — то есть с 88, потому что шапка 68 и отступ 20. Центр у него тот же самый.
 *
 * **На стенде это видно не буквально, и вот почему.** Стенд работает в демо-режиме, а там над
 * содержимым стоит полоса «гостевая сессия» — 90 px на телефоне и 39 на широком экране. Она
 * сдвигает начало содержимого вниз (замер: 178 вместо 88), и на стенде третья фаза показывает 546
 * вместо 456. У врача этой полосы нет вовсе. Вычитать её здесь не стали намеренно: величина
 * зависит от переноса строки, а лечить это пришлось бы либо переменной у самой полосы, либо
 * переводом `Main` во flex-колонку — то есть правкой несущей раскладки ради демонстрационного
 * случая.
 *
 * Ставится там, где ожидание **и есть вся страница** — ранний возврат до того, как нарисовано
 * хоть что-нибудь. Там, где над лоадером уже стоит панель записи (клиническая рекомендация) или он
 * ждёт внутри готовой страницы (дозагрузка ленты новостей, кадр читалки, окно импорта), высоту
 * задавать нельзя: страница станет длиннее окна ровно на то, что нарисовано выше.
 */
export function PageLoader() {
  return (
    <Stack
      align="center"
      justify="center"
      mih="calc(100vh - var(--app-shell-header-offset, 0px) - 2 * var(--app-shell-padding, 0px))"
    >
      <Loader />
    </Stack>
  );
}
