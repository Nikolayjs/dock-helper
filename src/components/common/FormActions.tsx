import type { ReactNode } from 'react';

import { useScrollDirection } from '../layout/useScrollDirection';
import classes from './FormActions.module.css';

/**
 * Держит действия формы на виду, вместо того чтобы оставлять их в конце страницы.
 *
 * Содержимое передаётся как есть — у форм разный набор кнопок, и навязывать им одну раскладку
 * значило бы переписывать каждую. Панель отвечает только за то, чтобы они не уезжали за экран.
 *
 * **На телефоне она уезжает при листании вниз и возвращается при листании вверх** — ровно как шапка
 * приложения и панель читалки. Причина замером: на экране 844 px панель занимает 67–73 px, то есть
 * 9 % высоты, и это поверх собственной нижней панели браузера — вместе они съедают около четверти
 * экрана у формы, которую и так листают.
 *
 * Прячется она только при листании **вниз**: это движение означает «читаю дальше», а не «сохраняю».
 * Любое движение вверх возвращает её тем же жестом, которым достают шапку.
 *
 * **В самом низу страницы панель есть всегда.** Иначе врач, долиставший форму до конца, не нашёл бы
 * «Сохранить» ровно там, где за ним и тянется, — то же враньё, из-за которого в этом приложении
 * переделывали кнопку «назад».
 */
export function FormActions({ children }: { children: ReactNode }) {
  const { visible, atBottom } = useScrollDirection();

  // Метка нужна тем, кто считает, сколько места осталось до низа окна: панель прилипшая и
  // перекрывает нижнюю полосу экрана — см. `useFittedHeight`. Она остаётся и у спрятанной панели:
  // место в раскладке та занимает по-прежнему, уезжает только картинка.
  return (
    <div className={visible || atBottom ? classes.bar : `${classes.bar} ${classes.hidden}`} data-form-actions>
      {children}
    </div>
  );
}
