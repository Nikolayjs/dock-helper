import { useSyncExternalStore } from 'react';

/**
 * Высота панели действий формы — для тех, кто рисует поверх неё.
 *
 * Кнопка «наверх» висит в правом нижнем углу окна и перекрывала «Сохранить»: замер на окне 857 px —
 * кружок кнопки ложился прямо на правый край панели, обрезая подпись. Раньше это лечилось отступом
 * `padding-right: 60px` у панели, но лечило только телефон (правило стояло под `48em`), а место
 * отнимало у кнопок навсегда — на экране, где его и так мало.
 *
 * Правильнее развести их по вертикали: кнопка «наверх» встаёт **над** панелью, а не поверх неё. Для
 * этого ей нужно знать высоту панели, и знать честно — панели у разных форм разной высоты (в одну
 * помещается «Сохранить», в другую ещё «Отмена» и «Удалить», а на узком экране они переносятся).
 *
 * Хранилище модульное, а не контекст: подписчик один, живёт в оболочке, а панель — где-то глубоко
 * на странице; тянуть провайдер через всё приложение ради одного числа не за чем. Значение —
 * состояние вне React, поэтому читается через `useSyncExternalStore`.
 */
let height = 0;
const listeners = new Set<() => void>();

export function setFormActionsHeight(value: number): void {
  if (value === height) return;
  height = value;
  for (const listener of listeners) listener();
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** Высота панели действий на этой странице; ноль — панели нет. */
export function useFormActionsHeight(): number {
  return useSyncExternalStore(
    subscribe,
    () => height,
    // На сервере панели нет: пререндер рисует лендинг, а он без форм.
    () => 0,
  );
}
