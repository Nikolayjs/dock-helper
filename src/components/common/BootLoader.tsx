import { Loader, Stack } from '@mantine/core';

/**
 * Ожидание загрузки приложения — одно на все его фазы.
 *
 * Фаз при перезагрузке две, и обе рисуют лоадер: сначала `RequireAuth` проверяет сохранённый токен,
 * потом `Suspense` ждёт чанк страницы. Высоту они объявляли себе порознь — 100vh и 60vh, — и лоадер
 * прыгал вверх на 180 px ровно в тот момент, когда врач на него смотрит. Замер на окне 900: центр
 * 450 один кадр, дальше 270 почти три секунды. Само ожидание при этом не кончалось — прыгала
 * картинка внутри него, то есть приложение выглядело так, будто уже загрузилось и начало заново.
 *
 * Поэтому высоту здесь называет **одно** место. Величина обязана быть во весь экран: пока лоадер
 * виден, оболочки нет вовсе (заглушка стоит выше `AppLayout` и подменяет его целиком), и центр
 * ожидания — это центр окна.
 */
export function BootLoader() {
  return (
    <Stack align="center" justify="center" mih="100vh">
      <Loader />
    </Stack>
  );
}
