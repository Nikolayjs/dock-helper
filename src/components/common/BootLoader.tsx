import { Loader, Stack } from '@mantine/core';

import { HEADER_HEIGHT } from '../../layouts/shellMetrics';

/**
 * Ожидание загрузки приложения — одно на все его фазы.
 *
 * Фаз при перезагрузке две, и обе рисуют лоадер: сначала `RequireAuth` проверяет сохранённый токен,
 * потом `Suspense` ждёт чанк страницы. Высоту они объявляли себе порознь — 100vh и 60vh, — и лоадер
 * прыгал вверх на 180 px ровно в тот момент, когда врач на него смотрит. Замер на окне 900: центр
 * 450 один кадр, дальше 270 почти три секунды. Само ожидание при этом не кончалось — прыгала
 * картинка внутри него, то есть приложение выглядело так, будто уже загрузилось и начало заново.
 *
 * Поэтому высоту здесь называет **одно** место. Величина — во весь экран: пока лоадер виден,
 * оболочки нет вовсе, заглушка стоит выше `AppLayout` и подменяет его целиком.
 *
 * **Но центрируется он не по окну, а по месту под шапкой**, и это третья правка той же жалобы.
 * Следом за этими двумя фазами идёт третья — страница грузит свои данные и показывает `PageLoader`,
 * а к тому моменту шапка уже нарисована и забрала верхние 68 px. Центрируйся здесь по всему окну —
 * и лоадер прыгал бы на её половину при появлении оболочки: замер на 390×844 давал 422 против 456.
 * Отступ сверху ровно в высоту шапки сводит все три фазы в одну точку; цена — на публичной части
 * такой заглушки нет вовсе, у неё своя (там шапки приложения не будет никогда).
 */
export function BootLoader() {
  return (
    <Stack align="center" justify="center" mih="100vh" pt={HEADER_HEIGHT}>
      <Loader />
    </Stack>
  );
}
