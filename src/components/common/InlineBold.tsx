import { Fragment } from 'react';
import { Text } from '@mantine/core';

/**
 * Текст, в котором `**жирным**` — жирное, и больше ничего.
 *
 * Своя разметка, а не markdown-библиотека, и причина та же, что у `writeDocx` и `writeXlsx`: на
 * входе не произвольный markdown, а наши собственные тексты сида, где из разметки есть ровно одно
 * начертание. Библиотека принесла бы заголовки, списки и ссылки, которых мы не пишем, и вес, за
 * который платил бы каждый.
 *
 * **Это не `SafeHtml` и не его замена.** Сюда попадает только то, что написали мы: заключения
 * анализаторов и заметки микробиологического справочника. Ничего не разбирается в HTML — строка
 * режется на куски и собирается React'ом, поэтому вставить сюда разметку нельзя в принципе.
 *
 * Разбор вынесен в чистую функцию и проверяется тестом: рендер-тестов в проекте нет вовсе, а
 * ошибиться здесь можно дважды — потерять текст и показать звёздочки.
 */
export interface BoldChunk {
  text: string;
  bold: boolean;
}

/**
 * Режет строку на куски по парам `**`.
 *
 * Непарная звёздочка остаётся текстом намеренно: в описаниях встречаются и «2**», и просто
 * опечатки, и показать звёздочку честнее, чем съесть половину фразы.
 */
export function splitBold(text: string): BoldChunk[] {
  // Нечётные элементы `split` с одной группой захвата — это и есть содержимое пар.
  return text
    .split(/\*\*(.+?)\*\*/g)
    .map((part, index) => ({ text: part, bold: index % 2 === 1 }))
    .filter((chunk) => chunk.text !== '');
}

export function InlineBold({ text }: { text: string }) {
  return (
    <>
      {splitBold(text).map((chunk, index) =>
        chunk.bold ? (
          <Text key={index} span fw={700} inherit>
            {chunk.text}
          </Text>
        ) : (
          <Fragment key={index}>{chunk.text}</Fragment>
        ),
      )}
    </>
  );
}
