import { describe, expect, it } from 'vitest';

import { splitBold } from './InlineBold';

/** Собранный обратно текст — то, что увидит врач; звёздочек в нём быть не должно. */
const flat = (text: string) =>
  splitBold(text)
    .map((chunk) => chunk.text)
    .join('');

describe('splitBold', () => {
  it('звёздочки уходят, а текст между ними помечается жирным', () => {
    expect(splitBold('Это **важно** знать')).toEqual([
      { text: 'Это ', bold: false },
      { text: 'важно', bold: true },
      { text: ' знать', bold: false },
    ]);
    expect(flat('Это **важно** знать')).toBe('Это важно знать');
  });

  it('обычный текст не меняется', () => {
    expect(splitBold('Просто фраза')).toEqual([{ text: 'Просто фраза', bold: false }]);
  });

  it('несколько выделений в одной строке', () => {
    expect(splitBold('**Раз** и **два**').filter((c) => c.bold).map((c) => c.text)).toEqual(['Раз', 'два']);
    expect(flat('**Раз** и **два**')).toBe('Раз и два');
  });

  it('выделение в начале не даёт пустого куска', () => {
    expect(splitBold('**Сразу** жирным')[0]).toEqual({ text: 'Сразу', bold: true });
  });

  /*
   * Непарная звёздочка — не разметка, а текст. Съесть половину фразы здесь хуже, чем показать
   * звёздочку: это заключение, которое читает врач.
   */
  it('непарная звёздочка остаётся текстом', () => {
    expect(flat('Доза **удвоена, а конца разметки нет')).toBe('Доза **удвоена, а конца разметки нет');
  });

  it('пустая строка даёт пустой список, а не кусок с пустым текстом', () => {
    expect(splitBold('')).toEqual([]);
  });

  /** Настоящее заключение из сида: проверяем, что оно доезжает целиком. */
  it('не теряет ни знака на настоящем тексте', () => {
    const real =
      'Положительный иммунохимический тест — **показание к колоноскопии**, а не к повторному анализу. ' +
      'Найденный геморрой не отменяет колоноскопию.';
    expect(flat(real)).toBe(real.replace(/\*\*/g, ''));
  });
});
