/**
 * Высота редактора на странице, где он — главное содержимое.
 *
 * Половина окна, но не меньше 320 px. Фиксированные 320 px были той самой «костыльной» высотой:
 * на ноутбучном окне редактор занимал треть экрана, под ним оставалась пустая страница, и документ
 * приходилось писать в щель, прокручивая её на каждом абзаце. Доля окна разумна именно у минимума:
 * это пол, а не потолок — текст растит поле дальше сам, и страница прокручивается как обычно.
 *
 * Строкой, а не числом: `max()` считает браузер, и пересчитывает сам при изменении размера окна —
 * мерить здесь нечего, поэтому и не меряем.
 */
export const EDITOR_MIN_HEIGHT = 'max(320px, 50vh)';
