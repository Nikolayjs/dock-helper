import { useMediaQuery } from '@mantine/hooks';

/**
 * Телефон ли это — один вопрос и один порог на всё приложение.
 *
 * Порог тот же, что у оболочки (`48em`): ниже него сайдбар становится выдвижной панелью, карточки
 * растягиваются во всю ширину, а таблицы уступают место компактным спискам.
 *
 * Значение по умолчанию — `false`, и оно осознанное: до первого замера страница рисуется как на
 * широком экране, а не мигает мобильной раскладкой на десктопе. `getInitialValueInEffect: false`
 * заставляет Mantine спросить браузер сразу, в первом же рендере, — иначе окно, открытое на
 * телефоне, успевало бы показать один кадр десктопной вёрстки.
 */
export function useIsMobile(): boolean {
  return useMediaQuery('(max-width: 48em)', false, { getInitialValueInEffect: false }) ?? false;
}
