import type { ReactNode } from 'react';
import { Card } from '@mantine/core';

import { PageToolbar } from './PageToolbar';

/**
 * Список раздела вместе со своей шапкой — на одной поверхности.
 *
 * До этого счётчик, поиск, фильтры и кнопки лежали **прямо на фоне страницы**, а таблица — на
 * карточке. Пока фон был серым, это читалось; с обоями шапка повисала на фотографии, и раздел
 * распадался на две части: неоформленные надписи сверху и аккуратная таблица под ними. Та же
 * причина, по которой на подложку переехали статья, заметка и карточка препарата, — только здесь
 * речь не о читаемости длинного текста, а о том, что элементы управления списком и есть часть
 * списка.
 *
 * Шапка отделена чертой, а не отступом: без неё поиск и первая строка таблицы читаются как одна
 * группа, и глаз не находит, где кончаются инструменты и начинаются данные.
 *
 * `padding={0}` у карточки и свои отступы у частей — потому что таблица держит отступы сама, а
 * дать ей общий отступ карточки значило бы отодвинуть её от краёв и оставить полосу пустоты вдоль
 * всей высоты списка.
 */
interface CatalogPanelProps {
  /** Вкладки раздела, если они есть: первая строка той же поверхности, а не отдельный остров. */
  tabs?: ReactNode;
  /** Счётчик, поиск, фильтры, кнопки — всё, чем управляют списком. */
  header: ReactNode;
  /** Таблица, компактный список или пустое состояние. */
  children: ReactNode;
}

export function CatalogPanel({ tabs, header, children }: CatalogPanelProps) {
  return (
    <PageToolbar tabs={tabs} content={children}>
      {header}
    </PageToolbar>
  );
}

/**
 * Только шапка — там, где под ней не таблица, а сетка карточек.
 *
 * Документы, бланки и калькуляторы показываются плитками, и класть плитки внутрь карточки нельзя:
 * получится карточка в карточке — та же ошибка, из-за которой чек-лист заметки лишился своей
 * рамки, попав на подложку. Поэтому здесь поверхность получает только шапка, а сетка остаётся как
 * была: каждая плитка и так стоит на своей.
 */
export function CatalogToolbar({ children }: { children: ReactNode }) {
  return (
    <Card withBorder padding="md">
      {children}
    </Card>
  );
}
